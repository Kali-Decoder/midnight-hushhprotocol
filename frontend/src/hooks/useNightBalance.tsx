"use client";

import {useCallback, useEffect, useState} from "react";
import {useAccount} from "@/lib/midnight/hooks";
import {
  DEFAULT_POOL_TOKEN,
  fromTokenUnits,
  POOL_TOKENS,
  toTokenUnits,
  type PoolToken,
} from "@/lib/config";
import {LoaderIcon} from "@/components/icons";

/** Poll a wallet balance every 12s while connected. */
function useWalletBalance(read: (() => Promise<bigint>) | null) {
  const [raw, setRaw] = useState<bigint>(0n);
  const [isLoading, setLoading] = useState(false);
  const [isFetching, setFetching] = useState(false);
  const [error, setError] = useState<Error | null>(null);

  const refetch = useCallback(async () => {
    if (!read) return;
    setFetching(true);
    try {
      setRaw(await read());
      setError(null);
    } catch (e) {
      setError(e instanceof Error ? e : new Error(String(e)));
    } finally {
      setFetching(false);
      setLoading(false);
    }
  }, [read]);

  useEffect(() => {
    if (!read) {
      setRaw(0n);
      return;
    }
    setLoading(true);
    void refetch();
    const t = window.setInterval(() => void refetch(), 12_000);
    return () => window.clearInterval(t);
  }, [read, refetch]);

  return {raw, isLoading, isFetching, error, refetch};
}

/** Unshielded NIGHT in the connected wallet. */
export function useTokenBalance(token: PoolToken = DEFAULT_POOL_TOKEN) {
  const {wallet, isConnected} = useAccount();
  const read = useCallback(() => wallet!.nightBalance(), [wallet]);
  const b = useWalletBalance(isConnected && wallet ? read : null);
  return {
    raw: b.raw,
    formatted: fromTokenUnits(b.raw, token.decimals),
    symbol: token.symbol,
    decimals: token.decimals,
    token,
    isLoading: isConnected && b.isLoading,
    isFetching: b.isFetching,
    error: b.error,
    refetch: b.refetch,
    hasEnough: (amountHuman: number) => b.raw >= toTokenUnits(amountHuman, token.decimals),
  };
}


/** DUST: the fee resource generated by held NIGHT (1 DUST = 10^15 Specks). */
export function useDustBalance() {
  const {wallet, isConnected} = useAccount();
  const read = useCallback(() => wallet!.dustBalance(), [wallet]);
  const b = useWalletBalance(isConnected && wallet ? read : null);
  return {
    raw: b.raw,
    formatted: formatDust(b.raw),
    symbol: "DUST",
    isLoading: isConnected && b.isLoading,
    isFetching: b.isFetching,
    error: b.error,
    refetch: b.refetch,
  };
}

function formatDust(raw: bigint): string {
  const s = fromTokenUnits(raw, 15);
  const [whole, frac = ""] = s.split(".");
  const trimmed = frac.slice(0, 4).replace(/0+$/, "");
  return trimmed ? `${whole}.${trimmed}` : whole;
}

function BalanceRow({
  label,
  amount,
  symbol,
  isLoading,
  isFetching,
  onRefresh,
  compact = false,
  className = "",
}: {
  label: string;
  amount: string;
  symbol: string;
  isLoading: boolean;
  isFetching: boolean;
  onRefresh: () => void;
  compact?: boolean;
  className?: string;
}) {
  return (
    <div
      className={`flex items-center justify-between gap-3 rounded-xl bg-paper/80 px-4 py-3 ${className}`}
    >
      <div className="min-w-0">
        <p className="text-xs text-graphite">{label}</p>
        {isLoading ? (
          <div className="mt-1 flex items-center gap-2 text-sm text-graphite">
            <LoaderIcon className="h-3.5 w-3.5 animate-spin" />
            Loading…
          </div>
        ) : (
          <p
            className={`mt-0.5 font-bold tracking-tight ${
              compact ? "text-lg" : "text-2xl"
            }`}
          >
            {amount}{" "}
            <span className="text-sm font-semibold text-graphite">{symbol}</span>
          </p>
        )}
      </div>
      <button
        type="button"
        onClick={onRefresh}
        disabled={isFetching}
        className="shrink-0 text-xs font-medium text-graphite hover:text-ink disabled:opacity-50"
      >
        {isFetching ? "…" : "Refresh"}
      </button>
    </div>
  );
}

export function TokenBalance({
  token = DEFAULT_POOL_TOKEN,
  label,
  className = "",
  compact = false,
}: {
  token?: PoolToken;
  label?: string;
  className?: string;
  compact?: boolean;
}) {
  const {isConnected} = useAccount();
  const {formatted, symbol, isLoading, refetch, isFetching} =
    useTokenBalance(token);

  if (!isConnected) return null;

  return (
    <BalanceRow
      label={label ?? `${symbol} balance`}
      amount={formatted}
      symbol={symbol}
      isLoading={isLoading}
      isFetching={isFetching}
      onRefresh={() => void refetch()}
      compact={compact}
      className={className}
    />
  );
}

export function DustBalance({
  label = "DUST (fees)",
  className = "",
  compact = false,
}: {
  label?: string;
  className?: string;
  compact?: boolean;
}) {
  const {isConnected} = useAccount();
  const {formatted, symbol, isLoading, refetch, isFetching} = useDustBalance();

  if (!isConnected) return null;

  return (
    <BalanceRow
      label={label}
      amount={formatted}
      symbol={symbol}
      isLoading={isLoading}
      isFetching={isFetching}
      onRefresh={() => void refetch()}
      compact={compact}
      className={className}
    />
  );
}

/** DUST + NIGHT balances for the account screen. */
export function AccountBalances({className = ""}: {className?: string}) {
  const {isConnected} = useAccount();
  if (!isConnected) return null;

  return (
    <div className={`flex flex-col gap-3 ${className}`}>
      <DustBalance />
      {POOL_TOKENS.filter((t) => t.enabled).map((t) => (
        <TokenBalance key={t.address} token={t} label={`Wallet ${t.symbol}`} />
      ))}
    </div>
  );
}
